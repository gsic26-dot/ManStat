export interface EvaluationIndicator {
  id: string;              // e.g. "1.1", "1.2", "c2.1", "c3.1"
  code: string;            // Official numbering e.g. "1.1", "1"
  name: string;            // หัวข้อการปฏิบัติงาน
  description: string;     // รายละเอียดระดับการปฏิบัติที่คาดหวังตามมาตรฐานวิทยฐานะ
  maxScore: number;        // คะแนนเต็มของตัวชี้วัด (ปกติ 4 คะแนน)
}

export interface EvaluationDomain {
  id: string;              // e.g. "domain_1", "domain_2"
  domainNumber: number;    // 1, 2, 3, 4, 5
  name: string;            // ชื่อด้าน เช่น "ด้านที่ 1 ด้านการจัดการเรียนรู้"
  indicators: EvaluationIndicator[];
}

export interface ChallengeItem {
  id: string;              // e.g. "challenge_process", "challenge_quantity", "challenge_quality"
  code: string;            // e.g. "1", "2.1", "2.2"
  name: string;
  description: string;
  maxScore: number;        // 20 หรือ 10
  levelScores: Record<1 | 2 | 3 | 4, number>; // ระดับ 1=25%, 2=50%, 3=75%, 4=100%
}

export interface EvaluationTemplate {
  key: EvaluationTemplateKey;
  officialFormNumber: string; // e.g. "แบบประเมินฯ 1", "แบบประเมินฯ 4"
  title: string;              // ชื่อแบบประเมินทางการ
  targetPosition: string;     // ตำแหน่งกลุ่มเป้าหมาย
  targetStanding: string;     // วิทยฐานะกลุ่มเป้าหมาย
  hasChallengePart: boolean;  // มีส่วนประเด็นท้าทาย (ตอนที่ 2) หรือไม่
  component1: {
    title: string;
    maxScore: number;         // 80
    part1: {
      title: string;
      maxScore: number;       // 80 (ครูผู้ช่วย) หรือ 60 (วิทยฐานะอื่น)
      domains: EvaluationDomain[];
    };
    part2?: {
      title: string;
      maxScore: number;       // 20
      items: ChallengeItem[];
    };
  };
}

