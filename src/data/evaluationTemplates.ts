/**
 * Returns summary of indicator counts for auditing
 */
export function getTemplateIndicatorCountSummary() {
  return Object.values(EVALUATION_TEMPLATES).map((tmpl) => {
    const part1Count = tmpl.component1.part1.domains.reduce(
      (acc, d) => acc + d.indicators.length,
      0
    );
    const part2Count = tmpl.component1.part2?.items.length ?? 0;
    const comp2Count = 1;
    const comp3Count = COMPONENT_3_CONFIG.items.length;
    return {
      key: tmpl.key,
      title: tmpl.title,
      domainsCount: tmpl.component1.part1.domains.length,
      part1Indicators: part1Count,
      part2Items: part2Count,
      comp2Items: comp2Count,
      comp3Items: comp3Count,
      totalItems: part1Count + part2Count + comp2Count + comp3Count,
    };
  });
}
