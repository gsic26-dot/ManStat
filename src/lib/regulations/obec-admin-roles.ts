/**
 * Returns default Thai academic year (พ.ศ.) based on Thai school calendar (May 16 – May 15).
 */
export function getCurrentThaiAcademicYear(date: Date = new Date()): string {
  const yearBE = date.getFullYear() + 543;
  const month = date.getMonth() + 1;
  const day = date.getDate();
  if (month < 5 || (month === 5 && day < 16)) {
    return String(yearBE - 1);
  }
  return String(yearBE);
}
