}

function Test-CommandExists {
    param([string]$CmdName);
    $cmd = Get-Command -Name $CmdName -ErrorAction SilentlyContinue;
    return ($null -ne $cmd);
}

function Invoke-ClaspTool {
    param([string[]]$ClaspArgs);
    if (Test-CommandExists -CmdName "clasp") {
        & clasp @ClaspArgs;
    } elseif (Test-CommandExists -CmdName "npx") {
        & npx clasp @ClaspArgs;
    } else {
        Write-Host "[ERR] 'CLASP' DEPENDENCY MISSING." -ForegroundColor Red;
        $global:LASTEXITCODE = 1;
    }
}

function Optimize-Workspace {
    $curPath = (Get-Location).Path;
    $gitIgnore = Join-Path -Path $curPath -ChildPath ".gitignore";
    $claspIgnore = Join-Path -Path $curPath -ChildPath ".claspignore";
    
    $sysFiles = @("_Backups/", "ClaspMaster.ps1", "Start_ClaspMaster.cmd", "FLIGHT_MANUAL.txt");
    
    if (-not (Test-Path -Path $gitIgnore)) {
        $lines = @("# Auto-generated by ClaspMaster") + $sysFiles + @("node_modules/", ".clasp.json");
        Set-Content -Path $gitIgnore -Value $lines -Encoding UTF8;
    } else {
        $lines = @(Get-Content -Path $gitIgnore);
        foreach ($f in $sysFiles) {
            if ($lines -notcontains $f) { Add-Content -Path $gitIgnore -Value $f -Encoding UTF8; }
        }
    }

    if (-not (Test-Path -Path $claspIgnore)) {
        $lines = @("# Auto-generated by ClaspMaster") + $sysFiles + @("node_modules/", ".git/", "package*.json");
        Set-Content -Path $claspIgnore -Value $lines -Encoding UTF8;
    } else {
        $lines = @(Get-Content -Path $claspIgnore);
        foreach ($f in $sysFiles) {
            if ($lines -notcontains $f) { Add-Content -Path $claspIgnore -Value $f -Encoding UTF8; }
        }
    }
}

function Get-WorkspaceStatus {
    $curPath = (Get-Location).Path;
    $curFolder = (Get-Item -Path $curPath).Name;
    $claspFile = Join-Path -Path $curPath -ChildPath ".clasp.json";
    $hasCfg = Test-Path -Path $claspFile;
    $scriptId = "NOT_LINKED";

    if ($hasCfg) {
        try {
            $rawText = Get-Content -Path $claspFile -Raw -ErrorAction Stop;
            $rawJson = ConvertFrom-Json -InputObject $rawText -ErrorAction Stop;
            if ($rawJson.scriptId) {
                $idStr = [string]($rawJson.scriptId);
                if ($idStr.Length -gt 20) {
                    $scriptId = $idStr.Substring(0, 10) + "..." + $idStr.Substring($idStr.Length - 6);
                } else {
                    $scriptId = $idStr;
                }
            }
        } catch {
            $scriptId = "INVALID_CONFIG";
        }
    }

    $result = New-Object PSObject -Property @{
        ProjectName = $curFolder;
        FullPath    = $curPath;
        HasClaspCfg = $hasCfg;
        ScriptId    = $scriptId;
    };
    return $result;
}

function New-WorkspaceBackup {
    param([string]$Tag = "ARCHIVE");
    $isSuccess = $false;
    try {
        $curPath = (Get-Location).Path;
        $backupRoot = Join-Path -Path $curPath -ChildPath "_Backups";
        if (-not (Test-Path -Path $backupRoot)) {
            $null = New-Item -Path $backupRoot -ItemType Directory -Force;
        }
        $projName = (Get-Item -Path $curPath).Name;
        $timeStr = Get-Date -Format "yyyyMMdd_HHmmss";
        $zipName = $projName + "_" + $Tag + "_" + $timeStr + ".zip";
        $destZip = Join-Path -Path $backupRoot -ChildPath $zipName;

        Write-Host "[SYS] EXECUTING ARCHIVE SEQUENCE..." -ForegroundColor DarkGray;
        
        $allItems = @(Get-ChildItem -Path $curPath);
        $backupItems = @();
        for ($i = 0; $i -lt $allItems.Count; $i++) {
            $item = $allItems[$i];
            if (($item.Name -ne "_Backups") -and ($item.Name -ne "node_modules") -and ($item.Name -ne ".git")) {
                $backupItems += $item.FullName;
            }
        }
        
        if ($backupItems.Count -gt 0) {
            Compress-Archive -Path $backupItems -DestinationPath $destZip -Force;
            Write-Host ("[OK] ARCHIVE SECURED: _Backups\" + $zipName) -ForegroundColor Green;
            $isSuccess = $true;
        }
    } catch {
        Write-Host ("[ERR] ARCHIVE FAILED: " + $_.Exception.Message) -ForegroundColor Red;
    }
    return $isSuccess;
}

function Test-AllJsSyntax {
    $syntaxResult = $true;
    if (-not (Test-CommandExists -CmdName "node")) { return $syntaxResult; }
    
    $curPath = (Get-Location).Path;
    $jsFiles = @(Get-ChildItem -Path $curPath -Filter "*.js" -File);
    if ($jsFiles.Count -eq 0) { return $syntaxResult; }

    Write-Host "[SYS] RUNNING SYNTAX DIAGNOSTICS..." -ForegroundColor DarkGray;
    for ($i = 0; $i -lt $jsFiles.Count; $i++) {
        $f = $jsFiles[$i];
        $fpath = $f.FullName;
        $errOut = & node --check "$fpath" 2>&1;
        if ($LASTEXITCODE -ne 0) {
            $syntaxResult = $false;
            Write-Host ("[FAIL] " + $f.Name) -ForegroundColor Red;
            $errStr = [string]$errOut;
            Write-Host ("       " + $errStr) -ForegroundColor DarkGray;
        } else {
            Write-Host ("[PASS] " + $f.Name) -ForegroundColor Green;
        }
    }
    return $syntaxResult;
}

